<pre><?php
// Teórica 5 — switch compara um valor com cada case; break termina o switch.
$dia = 3;
switch ($dia) {
    case 1:
        echo "Segunda";
        break;
    case 2:
        echo "Terça";
        break;
    case 3:
        echo "Quarta";
        break;
    default:
        echo "Outro dia";
}
?></pre>
